import { useEffect, useState } from 'react';
import { STANDALONE, api } from '../../api.js';
import { prefixProblem, tidyPrefix } from '../../../../shared/assetCode.js';

/**
 * EACH COMPANY'S ASSET CODE PREFIX.
 *
 * Dinesh: BNF-ASSETS-000001, BNV-ASSETS-000001, SENA-ASSETS-000001, with the
 * prefixes configurable. One running series per company, six digits.
 *
 * Two things this screen has to say out loud, because both are surprising
 * until somebody is told:
 *
 *   CHANGING A PREFIX NEVER REWRITES A CODE ALREADY ISSUED. Those codes are
 *   on stickers, on handover slips and on service bills. Only the NEXT one
 *   changes, and because it is a new series it starts again at 1.
 *
 *   A BLANK PREFIX IS NOT AN ERROR. It means nobody has chosen one and the
 *   company's initials are being used, which is shown rather than left to be
 *   discovered when the first sticker is printed.
 */
export default function AssetPrefixes({ onError, onToast }) {
  const [rows, setRows] = useState([]);
  const [typed, setTyped] = useState({});
  const [busy, setBusy] = useState(0);

  const load = async () => {
    try {
      const { companies } = await api.get('/people/assets/prefixes');
      setRows(companies || []);
    } catch (err) {
      onError(err);
    }
  };

  useEffect(() => {
    if (!STANDALONE) load();
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);

  if (STANDALONE) {
    return (
      <div className="card">
        <h3>Asset code prefixes</h3>
        <p className="muted small">
          Codes are generated by the server, so this is set there rather than in a file on a
          laptop.
        </p>
      </div>
    );
  }

  const save = async (row) => {
    const value = typed[row.id] ?? row.chosen;
    const problem = prefixProblem(value);
    if (problem) return onError(new Error(problem));
    setBusy(row.id);
    try {
      await api.put(`/people/assets/prefixes/${row.id}`, { prefix: tidyPrefix(value) });
      onToast?.('Saved. Codes already issued are unchanged.');
      setTyped((t) => ({ ...t, [row.id]: undefined }));
      await load();
    } catch (err) {
      onError(err);
    } finally {
      setBusy(0);
    }
  };

  return (
    <div className="card">
      <h3>Asset code prefixes</h3>
      <p className="muted small">
        Every new asset is given a code from its company’s own series —{' '}
        <code>BNF-ASSETS-000001</code>. The code is generated when the asset is saved, cannot be
        typed over, and a number is never handed out twice, even after an asset is deleted or
        written off.
      </p>

      {!rows.length ? (
        <p className="muted small">No companies yet.</p>
      ) : (
        <div className="scroll-x">
          <table className="sheet">
            <thead>
              <tr>
                <th>Company</th>
                <th>Prefix</th>
                <th className="num">Assets with a code</th>
                <th>Next code</th>
                <th />
              </tr>
            </thead>
            <tbody>
              {rows.map((row) => {
                const value = typed[row.id] ?? row.chosen;
                const changed = tidyPrefix(value) !== row.chosen;
                return (
                  <tr key={row.id}>
                    <td>
                      <strong>{row.name}</strong>
                      {!row.chosen && (
                        <div className="muted small">
                          using <strong>{row.prefix}</strong> — its initials, until you choose one
                        </div>
                      )}
                    </td>
                    <td>
                      <input
                        style={{ width: '7rem' }}
                        value={value}
                        placeholder={row.prefix}
                        onChange={(e) =>
                          setTyped((t) => ({ ...t, [row.id]: tidyPrefix(e.target.value) }))
                        }
                      />
                    </td>
                    <td className="num">{row.issued}</td>
                    <td className="muted small">
                      <code>{row.next}</code>
                    </td>
                    <td>
                      <button
                        className="tiny"
                        disabled={!changed || busy === row.id}
                        onClick={() => save(row)}
                      >
                        {busy === row.id ? 'Saving…' : 'Save'}
                      </button>
                    </td>
                  </tr>
                );
              })}
            </tbody>
          </table>
        </div>
      )}

      <p className="muted small" style={{ marginTop: '0.6rem' }}>
        Changing a prefix <strong>does not rewrite codes already issued</strong> — those are on
        stickers and signed slips. It changes only what the next one reads, and since that is a
        new series it starts again at 000001.
      </p>
    </div>
  );
}
